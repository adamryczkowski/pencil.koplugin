#!/usr/bin/env bash
# One-shot device probe. Writes ../device.env that the rest of the runner sources.
# Usage: ./detect-device.sh <kobo-ip> [ssh-port=2222]
set -euo pipefail

KOBO="${1:?usage: detect-device.sh <kobo-ip> [ssh-port=2222]}"
PORT="${2:-2222}"

SSH_CTRL="/tmp/koboctl-%r@%h:%p"
SSHOPTS=(-p "$PORT"
         -o "ControlMaster=auto"
         -o "ControlPath=${SSH_CTRL}"
         -o "ControlPersist=60s"
         -o "ConnectTimeout=5"
         -o "BatchMode=yes")

echo "Probing root@${KOBO}:${PORT} ..." >&2

PROBE=$(ssh "${SSHOPTS[@]}" "root@${KOBO}" '
  set -e
  echo "ARCH=$(uname -m)"
  echo "FBSZ=$(cat /sys/class/graphics/fb0/virtual_size 2>/dev/null || echo unknown)"
  echo "--- /proc/bus/input/devices ---"
  cat /proc/bus/input/devices
') || { echo "ssh probe failed" >&2; exit 1; }

echo
echo "$PROBE"
echo

ARCH=$(printf '%s\n' "$PROBE" | sed -n 's/^ARCH=//p')
FBSZ=$(printf '%s\n' "$PROBE" | sed -n 's/^FBSZ=//p')

case "$ARCH" in
  aarch64|x86_64) FMT="qqHHi"; BITS=64 ;;
  *)              FMT="IIHHi"; BITS=32 ;;
esac

W="${FBSZ%,*}"
H="${FBSZ#*,}"
[ -z "$W" ] || [ "$W" = "$FBSZ" ] && W="1404"
[ -z "$H" ] || [ "$H" = "$FBSZ" ] && H="1872"

OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/device.env"

cat > "$OUT" <<EOF
# Auto-generated by bin/detect-device.sh. Edit freely.
KOBO_HOST=$KOBO
KOBO_PORT=$PORT
KOBO_USER=root
KOBO_ARCH=$ARCH
KOBO_EVDEV_FMT=$FMT
KOBO_EVDEV_BITS=$BITS
KOBO_SCREEN_W=$W
KOBO_SCREEN_H=$H
KOBO_TOUCH_DEV=/dev/input/event1
KOBO_SCREENSHOT_DIR=/mnt/onboard/screenshots
KOBO_TAP_MARGIN=80
KOBO_SSH_CTRL=$SSH_CTRL
EOF

echo "Wrote $OUT:"
echo
cat "$OUT"
echo
echo "Verify:"
echo "  - KOBO_TOUCH_DEV is the touchscreen (look for 'Handlers=eventX' near 'Touchscreen' above)"
echo "  - KOBO_SCREEN_W/H match your model"
echo "  - KOBO_SCREENSHOT_DIR exists on the device"
echo "Edit $OUT if any of these are wrong."
